function robotsTxtController(req: Request, res: Response)
{
    const baseUrl = getBaseUrl(req);

    res.type('text/plain');
    res.setHeader('Cache-Control', 'public, max-age=3600');

    return res.send(
        [
            'User-agent: *',
            'Allow: /',
            '',
            `Sitemap: ${baseUrl}/sitemap.xml`,
            ''
        ].join('\n')
    );
}

function sitemapXmlController(req: Request, res: Response)
{
    const baseUrl = getBaseUrl(req);
    const urls = ['/', '/demo', '/faqs', '/contact', '/terms', '/privacy', '/refund-policy'];
    const today = new Date().toISOString().slice(0, 10);

    res.type('application/xml');
    res.setHeader('Cache-Control', 'public, max-age=3600');

    return res.send(`<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls.map(function (path)
    {
        const priority = path === '/' ? '1.0' : path === '/demo' ? '0.8' : '0.6';
        const changefreq = path === '/' || path === '/demo' ? 'weekly' : 'monthly';

        return `  <url>
    <loc>${xmlEscape(`${baseUrl}${path}`)}</loc>
    <lastmod>${today}</lastmod>
    <changefreq>${changefreq}</changefreq>
    <priority>${priority}</priority>
  </url>`;
    }).join('\n')}
</urlset>
`);
}

